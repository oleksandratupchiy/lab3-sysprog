"""Трансляція AST у читабельний автономний Python, без залежності від compiler."""
from . import ast_nodes as a
from .semantic import SemanticAnalyzer


PRELUDE = '''# Generated by Mini C. Python 3.11+, no third-party dependencies.
class _Runtime:
    def __init__(self, limit):
        if limit <= 0:
            raise ValueError("Step limit must be positive")
        self.limit = limit
        self.steps = 0

    def tick(self, location):
        self.steps += 1
        if self.steps > self.limit:
            raise RuntimeError(location + "execution step limit exceeded")

    def guard(self, condition, location):
        self.tick(location)
        return condition()

    @staticmethod
    def read(value, name, location):
        if value is None:
            raise RuntimeError(location + "uninitialized variable: " + name)
        return value

    @staticmethod
    def divide(left, right, location):
        if right == 0:
            raise RuntimeError(location + "division by zero")
        quotient = abs(left) // abs(right)
        return -quotient if (left < 0) != (right < 0) else quotient

    def remainder(self, left, right, location):
        return left - self.divide(left, right, location) * right


'''


class PythonGenerator:
    def generate(self, program, step_limit=100_000):
        if step_limit <= 0:
            raise ValueError('Ліміт кроків має бути додатним')
        self.bindings = SemanticAnalyzer().analyze(program)
        self.lines = [PRELUDE.rstrip(), '', '', f'def main(_step_limit={step_limit}):',
                      '    _rt = _Runtime(_step_limit)']
        self.statement(program.body, 1)
        self.lines.extend(['    return 0', '', '', "if __name__ == '__main__':",
                           '    main()', ''])
        return '\n'.join(self.lines)

    @staticmethod
    def location(node):
        return repr(f'{node.line}:{node.column}: ')

    def expression(self, node):
        if isinstance(node, a.IntegerLiteral):
            return str(node.value)
        if isinstance(node, a.Variable):
            return f'_rt.read({self.bindings[id(node)]}, {node.name!r}, {self.location(node)})'
        if isinstance(node, a.UnaryOp):
            operand = self.expression(node.operand)
            return f'int(not ({operand}))' if node.operator == '!' else f'({node.operator}({operand}))'
        left, right = self.expression(node.left), self.expression(node.right)
        op = node.operator
        if op in ('/', '%'):
            helper = 'divide' if op == '/' else 'remainder'
            return f'_rt.{helper}({left}, {right}, {self.location(node)})'
        if op in ('&&', '||'):
            operator = 'and' if op == '&&' else 'or'
            return f'int(bool({left}) {operator} bool({right}))'
        expression = f'({left} {op} {right})'
        return f'int({expression})' if op in ('==', '!=', '<', '<=', '>', '>=') else expression

    def emit(self, text, depth):
        self.lines.append('    ' * depth + text)

    def statement(self, node, depth):
        self.emit(f'_rt.tick({self.location(node)})', depth)
        if isinstance(node, a.Block):
            for statement in node.statements:
                self.statement(statement, depth)
        elif isinstance(node, a.Declaration):
            name = self.bindings[id(node)]
            self.emit(f'{name} = None', depth)
            if node.initializer is not None:
                self.emit(f'{name} = {self.expression(node.initializer)}', depth)
        elif isinstance(node, a.Assignment):
            self.emit(f'{self.bindings[id(node)]} = {self.expression(node.expression)}', depth)
        elif isinstance(node, a.Print):
            self.emit(f'print({node.format!r} % {self.expression(node.expression)}, end="")', depth)
        elif isinstance(node, a.Return):
            self.emit(f'return {self.expression(node.expression)}', depth)
        elif isinstance(node, a.If):
            self.emit(f'if {self.expression(node.condition)}:', depth)
            self.statement(node.then_branch, depth + 1)
            if node.else_branch is not None:
                self.emit('else:', depth)
                self.statement(node.else_branch, depth + 1)
        elif isinstance(node, a.While):
            self.emit(f'while _rt.guard(lambda: {self.expression(node.condition)}, {self.location(node.condition)}):', depth)
            self.statement(node.body, depth + 1)


def generate(program, step_limit=100_000):
    return PythonGenerator().generate(program, step_limit)